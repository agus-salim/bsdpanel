package vhost

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"runtime"
	"strings"
	"text/template"
)

type VHostConfig struct {
	Domain       string
	DocumentRoot string
	PhpVersion   string // "8.1", "8.2", "8.3", "none"
	PhpSocket    string // misal "/var/run/php83-fpm.sock"
	SSLEnabled   bool
	SSLCertPath  string
	SSLKeyPath   string
	LogsPath     string

	// Pengaturan Reverse Proxy
	IsReverseProxy bool
	ProxyTarget    string // misal "http://127.0.0.1:3000"
	ProxyWebSocket bool   // Support upgrade ke ws:// atau wss://
	ProxyBuffering bool   // ON / OFF
	MaxBodySizeMB  int    // Default 50MB
}

// Nginx Template komprehensif untuk FreeBSD (Mendukung PHP-FPM dan Reverse Proxy)
const nginxTemplate = `# Auto-generated by BSDPanel for {{ .Domain }}
server {
    listen 80;
    listen [::]:80;
    server_name {{ .Domain }} www.{{ .Domain }};

    {{- if .SSLEnabled }}
    # Redirect HTTP ke HTTPS
    location /.well-known/acme-challenge/ {
        root {{ .DocumentRoot }};
    }

    location / {
        return 301 https://$host$request_uri;
    }
}

server {
    listen 443 ssl http2;
    listen [::]:443 ssl http2;
    server_name {{ .Domain }} www.{{ .Domain }};

    ssl_certificate {{ .SSLCertPath }};
    ssl_certificate_key {{ .SSLKeyPath }};
    ssl_protocols TLSv1.2 TLSv1.3;
    ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384;
    ssl_prefer_server_ciphers off;
    {{- end }}

    root {{ .DocumentRoot }};
    client_max_body_size {{ if gt .MaxBodySizeMB 0 }}{{ .MaxBodySizeMB }}M{{ else }}64M{{ end }};

    access_log /var/log/nginx/{{ .Domain }}.access.log;
    error_log /var/log/nginx/{{ .Domain }}.error.log;

    {{- if .IsReverseProxy }}
    # Konfigurasi Reverse Proxy Nginx
    location / {
        proxy_pass {{ .ProxyTarget }};
        proxy_http_version 1.1;
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;

        {{- if .ProxyWebSocket }}
        # Support WebSocket Upgrade
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_read_timeout 86400s;
        proxy_send_timeout 86400s;
        {{- else }}
        proxy_read_timeout 120s;
        {{- end }}

        {{- if not .ProxyBuffering }}
        proxy_buffering off;
        {{- end }}
    }
    {{- else }}
    # Konfigurasi Standard Web Hosting / PHP
    index index.php index.html index.htm;

    location / {
        try_files $uri $uri/ /index.php?$query_string;
    }

    {{- if ne .PhpVersion "none" }}
    location ~ \.php$ {
        include fastcgi_params;
        fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;
        fastcgi_pass unix:{{ .PhpSocket }};
        fastcgi_index index.php;
    }
    {{- end }}

    location ~ /\.ht {
        deny all;
    }
    {{- end }}
}
`

// GenerateVHost membuat file konfigurasi web server dan memvalidasi keutuhan filenya
func GenerateVHost(serverType string, cfg VHostConfig, targetPath string) error {
	if cfg.PhpVersion != "none" && cfg.PhpSocket == "" && !cfg.IsReverseProxy {
		switch cfg.PhpVersion {
		case "8.1":
			cfg.PhpSocket = "/var/run/php81-fpm.sock"
		case "8.2":
			cfg.PhpSocket = "/var/run/php82-fpm.sock"
		case "8.3":
			cfg.PhpSocket = "/var/run/php83-fpm.sock"
		default:
			cfg.PhpSocket = "/var/run/php-fpm.sock"
		}
	}

	tmpl, err := template.New("vhost").Parse(nginxTemplate)
	if err != nil {
		return fmt.Errorf("gagal parse template vhost: %w", err)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, cfg); err != nil {
		return fmt.Errorf("gagal render template vhost: %w", err)
	}

	if targetPath != "" {
		_ = os.MkdirAll(filepath.Dir(targetPath), 0755)
		if err := os.WriteFile(targetPath, buf.Bytes(), 0644); err != nil {
			return fmt.Errorf("gagal menulis file konfigurasi: %w", err)
		}
	}

	return nil
}

// TestNginxConfig mengecek keabsahan syntax Nginx sebelum di-reload
func TestNginxConfig(ctx context.Context) (string, error) {
	if runtime.GOOS != "freebsd" {
		return "Syntax konfigurasi valid (simulasi mode development)", nil
	}

	cmd := exec.CommandContext(ctx, "/usr/local/sbin/nginx", "-t")
	out, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("uji konfigurasi Nginx gagal:\n%s", strings.TrimSpace(string(out)))
	}
	return strings.TrimSpace(string(out)), nil
}
